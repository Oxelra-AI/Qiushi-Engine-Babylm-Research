#!/usr/bin/env python3
"""research: acquisition-stream audit for dense-mask/sparse-label preservation controls.

Purpose
-------
The research preservation trainer changed the global torch seed as a function of
lambda_pres and inserted additional student forwards after the acquisition branch.
This script performs a no-model audit of the acquisition-example stream used by
the original research (M,S) implementation and by a clean preservation design.

It checks two separate facts:
  1. The row-keyed acquisition masks/labels are deterministic and independent of
     lambda_pres, because they are generated by stable_seed("view-focus", train_seed,
     row_key(row)) inside research/research.
  2. The research global seed actually differs across lambda_pres values, so the
     dropout/RNG stream during model training was not held fixed. A clean trainer
     should use the original research acquisition seed and preserve the RNG state
     around any auxiliary preservation student forward.

This is not a model-training result; it is an implementation-meaning audit.
"""
from __future__ import annotations

from pathlib import Path as _PublicPath
_PUBLIC_ROOT = next(p for p in _PublicPath(__file__).resolve().parents if (p / "CITATION.cff").is_file())
def _public_path(relative):
    return _PUBLIC_ROOT / relative


import argparse
import hashlib
import json
import pathlib
import sys
import time
from typing import Any, Dict, Iterable, List

import torch

ROOT = _public_path('.')
STUDY = _public_path('experiments/archive/functional_learning')
SCRIPTS = _public_path('experiments/archive/functional_learning/scripts')
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

# Import research first, then research to apply the actual dense-mask/sparse-label patch.
import real_stream_train_weighted as s64  # noqa: E402
import corrected_bridge_trainer as bridge  # noqa: E402
import densemask_sparselabel_train as s75  # noqa: F401,E402  # applies monkeypatch

DEFAULT_OUT = _public_path('experiments/archive/functional_learning/data/acquisition_stream_audit')


def rel(p: pathlib.Path | str) -> str:
    try:
        return str(pathlib.Path(p).resolve().relative_to(ROOT))
    except Exception:
        return str(p)


def now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def tensor_digest(t: torch.Tensor) -> str:
    arr = t.detach().cpu().contiguous().numpy()
    return hashlib.sha256(arr.tobytes()).hexdigest()


def update_rows(rows: List[Dict[str, Any]], update_i: int, words_per_update: int, cursor0: int) -> tuple[List[Dict[str, Any]], int, int]:
    macro_rows: List[Dict[str, Any]] = []
    words = 0
    cursor = cursor0
    while cursor < len(rows) and words < int(words_per_update):
        r = rows[cursor]
        macro_rows.append(r)
        words += int(r.get("words", s64.wc(r.get("text", ""))))
        cursor += 1
    return macro_rows, words, cursor


def digest_examples(examples: Iterable[Dict[str, Any]]) -> Dict[str, Any]:
    h = hashlib.sha256()
    n = 0
    focus_examples = 0
    ordinary_examples = 0
    focus_targets = 0
    ordinary_targets = 0
    by_source: Dict[str, int] = {}
    for ex in examples:
        n += 1
        component = str(ex.get("component"))
        row_key = str(ex.get("row_key"))
        source = str(ex.get("source", ""))
        by_source[source] = by_source.get(source, 0) + 1
        labels = ex["labels"]
        nt = int((labels != -100).sum().item())
        if component == "focus":
            focus_examples += 1
            focus_targets += nt
        else:
            ordinary_examples += 1
            ordinary_targets += nt
        h.update(component.encode("utf-8")); h.update(b"\0")
        h.update(row_key.encode("utf-8")); h.update(b"\0")
        h.update(source.encode("utf-8")); h.update(b"\0")
        h.update(tensor_digest(ex["input_ids"]).encode("ascii")); h.update(b"\0")
        h.update(tensor_digest(labels).encode("ascii")); h.update(b"\0")
        h.update(tensor_digest(ex["attention_mask"]).encode("ascii")); h.update(b"\0")
    return {
        "n_examples": n,
        "focus_examples": focus_examples,
        "ordinary_examples": ordinary_examples,
        "focus_targets": focus_targets,
        "ordinary_targets": ordinary_targets,
        "by_source": by_source,
        "sha256": h.hexdigest(),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tail-jsonl", type=pathlib.Path, default=s64.DEFAULT_TAIL)
    ap.add_argument("--out-dir", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--max-updates", type=int, default=5)
    ap.add_argument("--words-per-update", type=int, default=39533)
    ap.add_argument("--seq-length", type=int, default=512)
    ap.add_argument("--train-seed", type=int, default=62064)
    ap.add_argument("--mask-prob", type=float, default=0.15)
    ap.add_argument("--focus-prob", type=float, default=0.35)
    ap.add_argument("--max-focus-groups-per-row", type=int, default=16)
    ap.add_argument("--focus-lambda", type=float, default=0.15)
    ap.add_argument("--lambda-pres-values", nargs="+", type=float, default=[0.0, 1.0, 3.0])
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    # Put HF dynamic-module cache in writable output dir before tokenizer loading.
    hf = args.out_dir / "hf_cache"
    import os
    os.environ["HF_HOME"] = str(hf.resolve())
    os.environ["TRANSFORMERS_CACHE"] = str((hf / "transformers").resolve())
    os.environ["HF_MODULES_CACHE"] = str((hf / "modules").resolve())
    os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    (hf / "modules").mkdir(parents=True, exist_ok=True)

    rows, prefix_info = s64.load_prefix(args.tail_jsonl, int(args.max_updates), int(args.words_per_update))
    tokenizer = bridge.AutoTokenizer.from_pretrained(str(bridge.PARENT_PATH), local_files_only=True, use_fast=True)
    wgb = bridge.WordGroupBuilder(tokenizer)

    objective = "correspondence_focus_weighted"
    cursor = 0
    per_update: List[Dict[str, Any]] = []
    global_h = hashlib.sha256()
    for update_i in range(int(args.max_updates)):
        macro_rows, words, cursor = update_rows(rows, update_i, int(args.words_per_update), cursor)
        if not macro_rows:
            break
        examples, prep = s64.prepare_macro(
            macro_rows, tokenizer, int(args.seq_length), wgb, objective,
            int(args.train_seed), float(args.mask_prob), float(args.focus_prob), int(args.max_focus_groups_per_row)
        )
        d = digest_examples(examples)
        global_h.update(str(update_i).encode("ascii")); global_h.update(b"\0")
        global_h.update(d["sha256"].encode("ascii")); global_h.update(b"\0")
        per_update.append({
            "update": update_i + 1,
            "rows": len(macro_rows),
            "words": words,
            "prep": {k: (dict(v) if hasattr(v, "items") else v) for k, v in prep.items() if k != "focus_selected_pairs"},
            "digest": d,
        })
        if cursor >= len(rows):
            break

    original_seed = int(s64.stable_seed(bytes((115, 116, 101, 112, 48, 54, 52, 45, 114, 101, 97, 108, 45, 115, 116, 114, 101, 97, 109)).decode('utf-8'), objective, int(args.train_seed), float(args.focus_lambda)))
    seeds = {
        str(lp): int(s64.stable_seed(bytes((115, 116, 101, 112, 48, 56, 56, 45, 112, 114, 101, 115, 101, 114, 118, 97, 116, 105, 111, 110)).decode('utf-8'), int(args.train_seed), float(args.focus_lambda), float(lp)))
        for lp in args.lambda_pres_values
    }
    clean_seed = original_seed

    report = {
        "status": "ACQUISITION_STREAM_AUDIT_DONE",
        "created_utc": now(),
        "scientific_question": "Do preservation arms change the acquisition mask/label stream or stochastic training stream?",
        "tail_jsonl": rel(args.tail_jsonl),
        "prefix_info": prefix_info,
        "audited_updates": len(per_update),
        "objective": objective,
        "acquisition_constructor": "research prepare_macro after research dense-mask/sparse-label monkeypatch",
        "acquisition_digest_all_updates": global_h.hexdigest(),
        "per_update": per_update,
        "seed_audit": {
            "original_step075_global_seed": original_seed,
            "clean_preservation_global_seed_should_use": clean_seed,
            "global_seeds_by_lambda_pres": seeds,
            "lambda_changes_global_seed": len(set(seeds.values())) > 1,
            "interpretation": "Row-keyed masks/labels are lambda-independent, but research model dropout/RNG stream is lambda-dependent; clean trainer should use original seed and restore RNG after auxiliary forwards.",
        },
    }
    out_json = args.out_dir / "acquisition_stream_audit.json"
    out_md = args.out_dir / "acquisition_stream_audit.md"
    out_json.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = [
        "# research acquisition stream audit",
        "",
        f"Status: `{report['status']}`",
        f"Audited updates: `{len(per_update)}`",
        f"Acquisition digest: `{report['acquisition_digest_all_updates']}`",
        "",
        "## Seed audit",
        f"Original research/research acquisition global seed: `{original_seed}`",
        f"research seeds by lambda_pres: `{seeds}`",
        "",
        "Interpretation: acquisition masks/labels are deterministic from row keys, but research did not hold the model dropout/RNG stream fixed across preservation strengths.",
        "",
        "## Per update",
    ]
    for r in per_update:
        lines.append(f"- u{r['update']:04d}: rows {r['rows']}, words {r['words']}, focus targets {r['digest']['focus_targets']}, ordinary targets {r['digest']['ordinary_targets']}, sha `{r['digest']['sha256']}`")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"status": report["status"], "out_json": rel(out_json), "out_md": rel(out_md), "digest": report["acquisition_digest_all_updates"]}, indent=2), flush=True)


if __name__ == "__main__":
    main()
