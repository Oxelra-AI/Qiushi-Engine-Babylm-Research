#!/usr/bin/env python3
"""Full official-compatible evaluation wrapper for the
Strict-Small-tokenizer compact_view_reinvest seed43022 retrain.

Reuses the robust COMPACT_EXPERIENCE full evaluator, pointing it at the trained
run directory whose checkpoints carry the compliant 16k tokenizer trained only
on the 10M compact-view pool (tokenizer SHA-256
4a95a2a2ead21813a409c5ad7c2c008fbf418dcf3e0dc17bd970bd9ce25ea738).

This produces the zero-shot columns and (Super)GLUE column. Pristine 7,618-row
EWoK and official min-context-zero AoA are recomputed separately with the
research/research staging path, then collated with the unmodified official
collator, exactly as done for the two prior reinvest seeds.
"""
from __future__ import annotations

import pathlib
import sys

USER_ROOT = pathlib.Path(".").resolve()
COMPACT_EXPERIENCE_SCRIPTS = USER_ROOT / "experiments/archive" / 'compact_experience' / "scripts"
if str(COMPACT_EXPERIENCE_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(COMPACT_EXPERIENCE_SCRIPTS))

import full_overall_eval_runner as base  # noqa: E402

A01_WORKSPACE = USER_ROOT / "experiments/archive" / 'representation_and_objectives'
A01_RUN_BASE = A01_WORKSPACE / "training" / "runs"
PRISTINE_STRICT = A01_WORKSPACE / "data" / "pristine_official_coordinate" / "babylm-eval" / "strict"
GLOBALPIQA_GENERATED = A01_WORKSPACE / "data" / "globalpiqa_official_lineage" / "official_dl_scratch" / "generated_by_current_official_dl" / "evaluation_data" / "full_eval"

# Run subprocesses from the pristine current official checkout. The older INITIAL_MODEL_STUDIES
# checkout has a patched finetune/classifier_model.py; this override keeps
# SuperGLUE on the current official code coordinate. GlobalPIQA data are not
# checked into the pristine checkout until dl.py is run, so point those two
# columns at the research files generated by the current official dl.py and shown
# byte-identical to INITIAL_MODEL_STUDIES.
base.STRICT = PRISTINE_STRICT
for _task in base.ZERO_SHOT_TASKS:
    if _task["column"] == "GlobalPIQA_parallel":
        _task["data_path"] = str((GLOBALPIQA_GENERATED / "global_piqa_parallel").resolve())
    elif _task["column"] == "GlobalPIQA_nonparallel":
        _task["data_path"] = str((GLOBALPIQA_GENERATED / "global_piqa_nonparallel").resolve())

base.OUT_ROOT = A01_WORKSPACE / "data" / "strictsmalltok_seed43022_full_eval"
base.PER_TARGET_DIR = base.OUT_ROOT / "per_target"
base.TARGETS = {
    "strictsmalltok_reinvest_seed43022": {
        "run_dir": A01_RUN_BASE / "strictsmalltok_compact_view_reinvest_seed43022",
        "endpoint": "chck_100M",
        "description": (
            "Compact_view_reinvest seed43022 retrained from random weights with a "
            "16k tokenizer learned only from the compliant 10M compact-view pool "
            "(cleanqwen_fineweb_compact_view_reinvest_10M.jsonl). Single-factor "
            "tokenizer change vs the inherited-tokenizer 42.0331 endpoint; identical "
            "100M stream (SHA 3dd19f...), architecture, seeds, and recipe. Full "
            "official-compatible evaluation to determine whether the compact-view "
            "route survives a Strict-Small-budget representation."
        ),
        "family": "representation_and_objectives_strictsmalltok_reinvest_seed43022",
    }
}
base.ZERO_BY_COL = {t["column"]: t for t in base.ZERO_SHOT_TASKS}

if __name__ == "__main__":
    base.main()
