#!/usr/bin/env python3
"""research: OFFICIAL-DATA EWoK re-evaluation for compact_view_reinvest seed43022.

research established that the local vendored evaluation_data/full_eval/ewok_filtered
(6666 rows, 7 undercounted domains) does NOT match the pristine official EWoK
filtered data (7618 rows), which the official collator constants (EWOK_SIZES,
total 7618) exactly agree with. The research full-eval EWoK score 53.67 was
therefore computed against undercounted local data, not the official EWoK set.

This script re-scores EWoK on the PRISTINE regenerated ewok_filtered (7618 rows)
using the identical official invocation research used:
  evaluation_pipeline.sentence_zero_shot.run --task ewok --backend mlm
  --min_temperature default 1.0, --batch_size 64, --save_predictions.
It reuses the already-trained seed43022 chck_100M endpoint; no retraining,
no data regeneration here (the pristine ewok_filtered was regenerated by
ewok_regen_and_compare.py inside the pristine checkout).

Because the official eval code lives in the INITIAL_MODEL_STUDIES strict repo, we run from that
repo cwd but pass an absolute --data_path pointing at the PRISTINE ewok_filtered
directory. This keeps official code unmodified and only changes which EWoK data
file is scored.
"""
from __future__ import annotations

from pathlib import Path as _PublicPath
_PUBLIC_ROOT = next(p for p in _PublicPath(__file__).resolve().parents if (p / "CITATION.cff").is_file())
def _public_path(relative):
    return _PUBLIC_ROOT / relative


import argparse
import json
import math
import os
import pathlib
import re
import subprocess
import sys
import time

WORKSPACE = _public_path('experiments/archive/representation_and_objectives')  # .../representation_and_objectives/workspace
STUDY = _public_path('experiments/archive/representation_and_objectives')
USER_ROOT = _public_path('.')
ROOT_INITIAL_MODEL_STUDIES = _public_path('experiments/archive/initial_model_studies')
STRICT = _public_path('experiments/archive/initial_model_studies/repos/babylm-eval/strict')
PRISTINE_EWOK = _public_path('experiments/archive/representation_and_objectives/data/pristine_official_coordinate/babylm-eval/strict/evaluation_data/full_eval/ewok_filtered')
MODEL_PATH = _public_path('experiments/archive/frontier_consolidation/training/runs/cleanqwen_fineweb_compact_view_reinvest_16k_seed43022/hf_model/chck_100M')
OUT_ROOT = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval')


def now_utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def parse_sentence_score(text: str):
    for pat in [
        r"### AVERAGE [A-Z_ '\\-]*\s*\n\s*([+-]?[0-9]+(?:\.[0-9]+)?)",
        r"AVERAGE ACCURACY\s*\n\s*([+-]?[0-9]+(?:\.[0-9]+)?)",
    ]:
        m = re.search(pat, text)
        if m:
            val = float(m.group(1))
            if math.isfinite(val) and -5.0 <= val <= 105.0:
                return val
            return None
    return None


def read_report_score(task_out: pathlib.Path):
    candidates = sorted(task_out.rglob("best_temperature_report.txt"), key=lambda p: (p.stat().st_mtime, str(p)))
    for p in reversed(candidates):
        val = parse_sentence_score(p.read_text(encoding="utf-8", errors="replace"))
        if val is not None:
            return val, str(p)
    return None, None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpu", type=int, default=0)
    args = ap.parse_args()

    t0 = time.time()
    OUT_ROOT.mkdir(parents=True, exist_ok=True)
    hf = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval/hf_cache')
    tmp = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval/tmp')
    env = os.environ.copy()
    env["HF_HOME"] = str((hf).resolve())
    env["HF_HUB_CACHE"] = str((hf / "hub").resolve())
    env["HF_DATASETS_CACHE"] = str((hf / "datasets").resolve())
    env["TRANSFORMERS_CACHE"] = str((hf / "transformers").resolve())
    env["HF_MODULES_CACHE"] = str((hf / "modules").resolve())
    env["TOKENIZERS_PARALLELISM"] = "false"
    env["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
    env["TMPDIR"] = str(tmp.resolve())
    env.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
    for key in ["HF_HOME", "HF_HUB_CACHE", "HF_DATASETS_CACHE", "TRANSFORMERS_CACHE", "HF_MODULES_CACHE", "TMPDIR"]:
        pathlib.Path(env[key]).mkdir(parents=True, exist_ok=True)

    # Confirm pristine EWoK data present and count rows.
    domain_counts = {}
    for p in sorted(PRISTINE_EWOK.glob("*.jsonl")):
        domain_counts[p.stem] = sum(1 for _ in p.open())
    total_rows = sum(domain_counts.values())

    revision = "official_ewok_reinvest"
    task_out = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval/official_outputs/EWoK')
    task_out.mkdir(parents=True, exist_ok=True)
    log = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval/logs/ewok_reeval.log')
    log.parent.mkdir(parents=True, exist_ok=True)

    cmd = [
        sys.executable, "-m", "evaluation_pipeline.sentence_zero_shot.run",
        "--model_path_or_name", str(MODEL_PATH),
        "--backend", "mlm",
        "--task", "ewok",
        "--data_path", str(PRISTINE_EWOK),
        "--revision_name", revision,
        "--save_predictions",
        "--batch_size", "64",
        "--non_causal_batch_size", "64",
        "--output_dir", str(task_out.resolve()),
    ]
    with log.open("a", encoding="utf-8") as f:
        f.write(f"\n[{now_utc()}] $ {' '.join(cmd)}\n")
        proc = subprocess.run(cmd, cwd=str(_public_path('experiments/archive/initial_model_studies/repos/babylm-eval/strict')), env=env, stdout=f, stderr=subprocess.STDOUT, text=True, timeout=3600)
    score, report_path = read_report_score(task_out)
    pred = None
    preds = sorted(task_out.rglob("predictions.json"), key=lambda p: (p.stat().st_mtime, str(p)))
    if preds:
        pred = str(preds[-1])
        # Count prediction items to confirm they are on the 7618-row data.
        try:
            with open(pred, "r", encoding="utf-8") as pf:
                pdata = json.load(pf)
            pred_total = sum(len(v.get("predictions", [])) if isinstance(v, dict) else 0 for v in pdata.values()) if isinstance(pdata, dict) else None
        except Exception:
            pred_total = None
    else:
        pred_total = None

    ewok = 53.67
    payload = {
        "status": "OFFICIAL_EWOK_REEVAL_DONE",
        "created_utc": now_utc(),
        "model_path": str(MODEL_PATH),
        "pristine_ewok_dir": str(PRISTINE_EWOK),
        "pristine_ewok_domain_counts": domain_counts,
        "pristine_ewok_total_rows": total_rows,
        "returncode": proc.returncode,
        "official_ewok_score": score,
        "report_path": report_path,
        "predictions_path": pred,
        "prediction_item_total": pred_total,
        "local_ewok_score": ewok,
        "delta_official_minus_local": (score - ewok) if score is not None else None,
        "log": str(log),
        "elapsed_sec": time.time() - t0,
        "interpretation": (
            "EWoK re-scored on the pristine official 7618-row ewok_filtered data, reusing the "
            "trained seed43022 chck_100M endpoint with the identical official invocation used in "
            "research. Compare official_ewok_score against the research local EWoK 53.67 to correct "
            "the EWoK column of the 42.0868 Overall on the pristine official coordinate."
        ),
    }
    out_json = _public_path('experiments/archive/representation_and_objectives/data/official_ewok_reeval/official_ewok_reeval.json')
    out_json.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({
        "status": payload["status"],
        "returncode": proc.returncode,
        "official_ewok_score": score,
        "local_ewok_score": ewok,
        "delta": payload["delta_official_minus_local"],
        "pristine_ewok_total_rows": total_rows,
        "prediction_item_total": pred_total,
        "out": str(out_json),
        "elapsed_sec": payload["elapsed_sec"],
    }, indent=2), flush=True)


if __name__ == "__main__":
    main()
